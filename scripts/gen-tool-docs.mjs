// Regenerates docs/tools.md from the tool definitions the server actually registers.
// Usage: npm run build && node scripts/gen-tool-docs.mjs
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/client';
import { InMemoryTransport } from '@modelcontextprotocol/server';
import { parseConfig } from '../dist/core/config.js';
import { silentLogger } from '../dist/core/logger.js';
import { createServer } from '../dist/mcp/server.js';
import { PixelBridge } from '../dist/services/pixelbridge.js';

const dir = mkdtempSync(path.join(os.tmpdir(), 'pb-docs-'));
// Mock providers so every tool (including optional ones) is registered.
const pb = new PixelBridge({
  projectRoot: dir,
  config: parseConfig({ providers: { mock: { enabled: true } } }),
  env: {},
  logger: silentLogger,
});
const [ct, st] = InMemoryTransport.createLinkedPair();
await createServer(pb).connect(st);
const client = new Client({ name: 'docs', version: '0' });
await client.connect(ct);
const { tools } = await client.listTools();
await client.close();
pb.close();
rmSync(dir, { recursive: true, force: true });

const typeOf = (s) => {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' \| ');
  if (s.anyOf) return s.anyOf.map(typeOf).join(' \| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.type === 'object') return 'object';
  return s.type ?? 'any';
};
const esc = (t) =>
  String(t ?? '')
    .replace(/\|/g, '\|')
    .replace(/\n/g, ' ');

let md = `<!-- Generated by scripts/gen-tool-docs.mjs from the registered tool schemas. Do not edit by hand. -->

# MCP tool reference

${tools.length} tools. \`generate_3d_from_image\` is only registered when a configured provider supports image-to-3D
(the Gemini API does not), so a typical installation exposes ${tools.length - 1}.

| Tool | Read-only | Summary |
| --- | --- | --- |
${tools.map((t) => `| [\`${t.name}\`](#${t.name}) | ${t.annotations?.readOnlyHint ? 'yes' : 'no'} | ${esc(t.title)} |`).join('\n')}
`;
for (const t of tools) {
  md += `\n## ${t.name}\n\n${t.description}\n\n`;
  const props = t.inputSchema.properties ?? {};
  const req = new Set(t.inputSchema.required ?? []);
  const names = Object.keys(props);
  if (!names.length) {
    md += '_No arguments._\n';
    continue;
  }
  md += '| Argument | Type | Required | Description |\n| --- | --- | --- | --- |\n';
  for (const n of names) {
    md += `| \`${n}\` | ${typeOf(props[n])} | ${req.has(n) ? 'yes' : ''} | ${esc(props[n].description)} |\n`;
  }
}
writeFileSync(new URL('../docs/tools.md', import.meta.url), md);
console.log(`docs/tools.md: ${tools.length} tools`);
